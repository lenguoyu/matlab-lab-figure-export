function write_lab_plotly_viewer(destination, entries)
%WRITE_LAB_PLOTLY_VIEWER Write the offline Plotly figure workbench.

    payload = jsonencode(reshape(num2cell(entries), 1, []));
    payload = strrep(payload, '<', '\u003C');
    payload = strrep(payload, char(8232), '\u2028');
    payload = strrep(payload, char(8233), '\u2029');

    [file, openMessage] = fopen(destination, 'w', 'n', 'UTF-8');
    if file < 0
        error('write_lab_plotly_viewer:OpenFailed', ...
            'Could not open figure workbench: %s', openMessage);
    end
    fileGuard = onCleanup(@() fclose(file));

    writeInterface(file);
    fprintf(file, '<script type="application/json" id="viewer-data">%s</script>\n', payload);
    writeViewerScript(file);
    fprintf(file, '</body></html>\n');

    [writeMessage, writeStatus] = ferror(file);
    if writeStatus ~= 0
        error('write_lab_plotly_viewer:WriteFailed', ...
            'Could not write figure workbench: %s', writeMessage);
    end
end

