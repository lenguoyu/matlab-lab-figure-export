function writeViewerScript(file)
    fprintf(file, '%s\n', strjoin({
        '<script>'
        'window.addEventListener("DOMContentLoaded", () => {'
        '  const select = document.getElementById("figure-select");'
        '  const title = document.getElementById("figure-title");'
        '  const status = document.getElementById("figure-status");'
        '  const message = document.getElementById("figure-message");'
        '  const notice = document.getElementById("renderer-status");'
        '  const preview = document.getElementById("preview-panel");'
        '  const plot = document.getElementById("plot");'
        '  const download = document.getElementById("download-spec");'
        '  let revision = 0;'
        '  let activePlot = null;'
        '  let entries;'
        ''
        '  function setText(element, text) {'
        '    element.textContent = text;'
        '    element.hidden = !text;'
        '  }'
        ''
        '  function setEmpty(titleText, noticeText) {'
        '    title.textContent = titleText;'
        '    select.replaceChildren(new Option(titleText));'
        '    setText(notice, noticeText);'
        '  }'
        ''
        '  function hasSpec(entry) {'
        '    return Array.isArray(entry?.spec?.data) && entry.spec.data.length > 0;'
        '  }'
        ''
        '  function fileStem(source) {'
        '    const name = String(source).split(/[\\/]/).pop().replace(/\.[^.]*$/, "");'
        '    return name.replace(/[<>:"/\\|?*\x00-\x1F]/g, "-").trim() || "figure";'
        '  }'
        ''
        '  function showPreview(entry, currentRevision, fallbackNotice = "") {'
        '    const path = entry.preview;'
        '    const canPreview = typeof path === "string" && /^previews\/[0-9]{4,}\.png$/.test(path);'
        '    setText(notice, fallbackNotice);'
        '    if (!canPreview) {'
        '      if (!fallbackNotice && !entry.message) setText(notice, "No preview is available for this figure.");'
        '      return;'
        '    }'
        '    const image = document.createElement("img");'
        '    image.id = "figure-preview";'
        '    image.alt = `Preview of ${entry.source}`;'
        '    image.decoding = "async";'
        '    image.addEventListener("error", () => {'
        '      if (currentRevision !== revision) return;'
        '      preview.hidden = true;'
        '      setText(notice, `${fallbackNotice} The preview could not load.`.trim());'
        '    });'
        '    preview.replaceChildren(image);'
        '    preview.hidden = false;'
        '    image.src = `./${path}`;'
        '  }'
        ''
        '  function dispose(target) {'
        '    if (!target || typeof window.Plotly?.purge !== "function") return;'
        '    try { window.Plotly.purge(target); } catch { /* The renderer may be partially initialized. */ }'
        '  }'
        ''
        '  async function render(index) {'
        '    const entry = entries[index];'
        '    const currentRevision = ++revision;'
        '    if (activePlot?.ready) dispose(activePlot.canvas);'
        '    activePlot = null;'
        '    plot.hidden = true;'
        '    plot.replaceChildren();'
        '    preview.hidden = true;'
        '    preview.replaceChildren();'
        ''
        '    const interactive = hasSpec(entry);'
        '    title.textContent = entry.source;'
        '    setText(status, entry.status);'
        '    status.dataset.kind = interactive ? "interactive" : entry.preview ? "static" : "unavailable";'
        '    setText(message, entry.message);'
        '    download.disabled = !interactive;'
        ''
        '    if (!interactive) {'
        '      showPreview(entry, currentRevision);'
        '      return;'
        '    }'
        '    if (typeof window.Plotly?.newPlot !== "function") {'
        '      showPreview(entry, currentRevision, "The local Plotly renderer could not load.");'
        '      return;'
        '    }'
        ''
        '    const canvas = document.createElement("div");'
        '    canvas.className = "plot-canvas";'
        '    const job = { canvas, ready: false };'
        '    activePlot = job;'
        '    plot.replaceChildren(canvas);'
        '    plot.hidden = false;'
        '    setText(notice, "Rendering interactive plot…");'
        '    try {'
        '      const spec = JSON.parse(JSON.stringify(entry.spec));'
        '      const layout = { ...spec.layout, autosize: true };'
        '      if (layout.grid?.rows > 1 && Number.isFinite(layout.height) && layout.height > 0) {'
        '        canvas.style.height = layout.height + "px";'
        '      }'
        '      delete layout.width;'
        '      delete layout.height;'
        '      const config = {'
        '        responsive: true, displaylogo: false, displayModeBar: true, scrollZoom: false,'
        '        showLink: false, showSendToCloud: false,'
        '        modeBarButtonsToRemove: ["sendDataToCloud", "editInChartStudio"],'
        '        toImageButtonOptions: { format: "svg", filename: fileStem(entry.source) }'
        '      };'
        '      await window.Plotly.newPlot(canvas, spec.data, layout, config);'
        '      job.ready = true;'
        '      if (currentRevision !== revision) {'
        '        dispose(canvas);'
        '        return;'
        '      }'
        '      setText(notice, "");'
        '    } catch (error) {'
        '      dispose(canvas);'
        '      if (currentRevision !== revision) return;'
        '      activePlot = null;'
        '      plot.hidden = true;'
        '      plot.replaceChildren();'
        '      showPreview(entry, currentRevision, "The interactive plot could not render for this figure.");'
        '    }'
        '  }'
        ''
        '  try {'
        '    entries = JSON.parse(document.getElementById("viewer-data").textContent);'
        '    if (!Array.isArray(entries)) throw new TypeError("Expected a list of figures");'
        '  } catch (error) {'
        '    setEmpty("Figure data unavailable", "The embedded figure list could not be read.");'
        '    return;'
        '  }'
        '  if (!entries.length) {'
        '    setEmpty("No figures", "This figure pack contains no entries.");'
        '    return;'
        '  }'
        '  select.replaceChildren(...entries.map((entry, index) => new Option(entry.source, String(index))));'
        '  select.disabled = false;'
        '  select.addEventListener("change", () => render(Number(select.value)));'
        '  download.addEventListener("click", () => {'
        '    const entry = entries[Number(select.value)];'
        '    if (!hasSpec(entry)) return;'
        '    const json = JSON.stringify(entry.spec, null, 2);'
        '    const url = URL.createObjectURL(new Blob([json], { type: "application/json" }));'
        '    const link = document.createElement("a");'
        '    link.href = url;'
        '    link.download = `${fileStem(entry.source)}.plotly.json`;'
        '    document.body.append(link);'
        '    link.click();'
        '    link.remove();'
        '    window.setTimeout(() => URL.revokeObjectURL(url), 1000);'
        '  });'
        '  render(0);'
        '});'
        '</script>'
        }, newline));
end
